# ---------- перепроверка критичных полей (сравнение с DeepSeek) ----------

COMPARE_PROMPT = """Сегодня: {today}.

Задание: перепроверка критичных полей. Для каждого поля ниже — наше значение и фрагмент, который независимо нашла \
другая модель (DeepSeek) в тех же документах. Она цитирует «как в тексте», поэтому формулировки могут отличаться — \
сравнивай смысл, числа и даты, а не форму записи.

{items}

Для каждого поля верни:
- verdict: «match» — совпадает по смыслу, числам и датам; «ours_confirmed» — расходится, но, перепроверив по тексту \
документов, ты подтверждаешь наше значение; «theirs_correct» — расходится и права другая модель (наше значение ошибочно \
или неполно); «not_found_by_them» — другая модель не нашла фрагмент, а у нас значение есть; «not_found_both» — у нас \
«Не указано в документах» и у неё тоже не найдено.
- final_value — итоговое значение в нашем формате и по нашим правилам: при «theirs_correct» — исправленное значение, \
иначе наше без изменений. Без маркеров ✅/🔺.
- their_version — кратко суть версии другой модели (для пометки о расхождении).
- comment — одно предложение: на чём основано решение (документ, пункт)."""


def compare_schema(keys: list[str]) -> dict:
    item = _obj({"verdict": {"type": "string", "enum": ["match", "ours_confirmed", "theirs_correct",
                                                        "not_found_by_them", "not_found_both"]},
                 "final_value": STR, "their_version": STR, "comment": STR})
    return _obj({k: item for k in keys})
