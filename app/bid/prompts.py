def _plan_head(today: str, participant: str, library: str, tender: str) -> str:
    return f"""Сегодня {today}. Задача — как в шагах «Участие в конкурсе» и «Подготовка пакета заявки»: найти требования \
к участнику и полный состав заявки по документации выше и сопоставить их со сведениями участника и его библиотекой \
документов.

<participant>
{participant}
</participant>

<library>
Библиотека документов участника (номер — файл — дата — для чего; «устарел/недействителен» — так и считать):
{library}
</library>

<tender>
{tender}
</tender>

"""


