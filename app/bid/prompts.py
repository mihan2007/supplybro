# Стандартный текст промта «bid.fill»: метку {tokens} программа заменяет списком меток цен; {{ЦЕНА…}} — сами метки.
FILL_RULES = """Как заполнять:
1. Подставляй сведения участника, закупки и позиций там, где форма их просит: подчёркивания «____», квадратные \
скобки «[указывается …]», пустые ячейки «Сведения об участнике». Не меняй текст формы, который участник не должен \
менять (обязательства, согласия, ссылки на документы заказчика).
2. «БЛАНК УЧАСТНИКА» (или «на бланке организации») — замени шапкой участника: полное наименование, ИНН/КПП, ОГРН, \
юридический адрес, телефон, e-mail.
3. Нет сведений — пиши ровно [[что нужно]] (например «[[номер письма]]», «[[срок поставки, дней]]»): в документе это \
станет пометкой «<нет данных>». Не оставляй пустыми поля, где должно быть значение. Строки для подписи, печати и даты \
подписания («_______ / Строк Т.В. /», ««___» ________ 2026 г.») оставляй как в форме — их заполняет участник при \
подписании; ФИО и должность подписанта впиши.
Ячейки «(номер — автоматически)» не трогай: номер строки в них ставит Word.
4. Цены, НДС, суммы прописью, снижение и паспортные данные руководителя НЕ пиши сам — только метки, их подставит \
программа: {tokens}. Для позиций — с номером позиции после двоеточия: {{ЦЕНА_ЕД_БЕЗ_НДС:3}}, \
{{СУММА_С_НДС:3}}.
5. Решения участника (срок действия оферты сверх требуемого, альтернативные предложения, субподрядчики, способ \
обеспечения) — если форма требует выбора, а документация и сведения участника его не задают: [[решение участника: …]]; \
необязательные строки про альтернативные предложения можно удалить, только если это прямо разрешено формой («при \
наличии», «если есть»).
6. Товар — строго как в техническом задании (наименование, марка/модель, количество, единица); производитель и страна \
происхождения — только если они есть в позициях; иначе [[…]].
7. Отвечай только правками; не повторяй неизменённый текст."""


def fill_prompt(doc_title: str, kind: str, markup: str, participant: str, tender: str, positions: str,
                tokens: str, extra: str, ps: Prompts | None = None) -> str:
    pos_block = f"\n<positions>\n{positions}\n</positions>\n" if positions else ""
    extra_block = f"\n<extra>\n{extra}\n</extra>\n" if extra else ""
    return f"""Заполни форму «{doc_title}» (вид: {kind}) от имени участника. Ниже — разметка формы: [А5] — абзац \
№ 5, [Т7] — таблица № 7, строки r0, r1…, ячейки c0, c1…

<form>
{markup}
</form>

<participant>
{participant}
</participant>

<tender>
{tender}
</tender>
{pos_block}{extra_block}
Ответ — список правок edits:
- {{"op": "par", "i": 5, "text": "…"}} — заменить текст абзаца [А5] целиком (оформление абзаца сохранится);
- {{"op": "replace", "i": 5, "find": "______", "text": "…"}} — заменить часть абзаца (find — точный фрагмент из него);
- {{"op": "cell", "i": 7, "r": 2, "c": 1, "text": "…"}} — записать текст в ячейку;
- {{"op": "cell_replace", "i": 7, "r": 2, "c": 1, "find": "…", "text": "…"}} — заменить часть ячейки;
- {{"op": "add_rows", "i": 7, "r": 2, "rows": [["1", "…", "…"], ["2", "…", "…"]]}} — добавить строки после строки \
r2 по её образцу (для таблиц позиций: по строке на позицию, ячейки по порядку столбцов; пустую строку-образец потом \
удалить нельзя — заполни её первой позицией, а остальные добавь);
- {{"op": "delete", "i": 3}} — удалить абзац (только служебный текст формы: «начало формы», «конец формы», \
«Инструкции по заполнению…» и сами инструкции).

""" + or_default(ps).render("bid.fill", tokens=tokens)
